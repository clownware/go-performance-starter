// TestMainVerdict drives main() in a child process (see TestMain) from a
// synthetic repo root and asserts the gate's verdict. This is the ADR-030 TC-1
// contract: every non-template key agrees with its source of truth, and a key
// with no wired check fails.
func TestMainVerdict(t *testing.T) {
	tests := []struct {
		name         string
		editManifest func(m map[string]string)
		editRepo     func(files map[string]string) // runs after versions.json is rendered
		wantExit     int
		wantOut      string // substring of combined stdout+stderr
	}{
		{
			name:     "manifest matching every pin passes and reports the key count",
			wantExit: 0,
			wantOut:  "✅ versions.json matches the repo's actual pins (15 keys)",
		},
		{
			name:         "drifted pin fails naming the key and both values",
			editManifest: func(m map[string]string) { m["htmx"] = "1.9.9" },
			wantExit:     1,
			wantOut:      `versions.json htmx = "1.9.9" but the repo actually pins "1.9.10"`,
		},
		{
			name:         "key missing from the manifest counts as drift",
			editManifest: func(m map[string]string) { delete(m, "node") },
			wantExit:     1,
			wantOut:      `versions.json node = "" but the repo actually pins "20"`,
		},
		{
			name:         "key with no wired check fails",
			editManifest: func(m map[string]string) { m["postgres"] = "16" },
			wantExit:     1,
			wantOut:      `versions.json key "postgres" has no check wired in scripts/checkversions`,
		},
		{
			name:         "template not in vX.Y.Z form fails",
			editManifest: func(m map[string]string) { m["template"] = "1.2.3" },
			wantExit:     1,
			wantOut:      `versions.json template "1.2.3" is not a vX.Y.Z tag`,
		},
		{
			name: "pin whose source of truth is empty fails",
			editRepo: func(files map[string]string) {
				files["go.mod"] = strings.Replace(files["go.mod"], "toolchain go1.91.2\n", "", 1)
			},
			wantExit: 1,
			wantOut:  `no in-repo source of truth found for "go"`,
		},
		{
			name:     "unreadable source of truth fails",
			editRepo: func(files map[string]string) { delete(files, "internal/database/db.go") },
			wantExit: 1,
			wantOut:  "internal/database/db.go",
		},
		{
			name:     "missing versions.json fails",
			editRepo: func(files map[string]string) { delete(files, "versions.json") },
			wantExit: 1,
			wantOut:  "versions.json",
		},
		{
			name:     "malformed versions.json fails",
			editRepo: func(files map[string]string) { files["versions.json"] = `{"template": ` },
			wantExit: 1,
			wantOut:  "parse versions.json",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			files := fakeRepo()
			manifest := fakeManifest()
			if tt.editManifest != nil {
				tt.editManifest(manifest)
			}
			raw, err := json.Marshal(manifest)
			if err != nil {
				t.Fatal(err)
			}
			files["versions.json"] = string(raw)
			if tt.editRepo != nil {
				tt.editRepo(files)
			}
			writeTree(t, root, files)

			exit, out := runMain(t, root)
			if exit != tt.wantExit {
				t.Fatalf("exit code = %d, want %d; output:\n%s", exit, tt.wantExit, out)
			}
			if !strings.Contains(out, tt.wantOut) {
				t.Errorf("output does not contain %q:\n%s", tt.wantOut, out)
			}
		})
	}
}

// runMain re-executes the test binary as the checkversions command with root
// as the working directory and returns its exit code and combined output.
func runMain(t *testing.T, root string) (int, string) {
	t.Helper()
	cmd := exec.Command(os.Args[0])
	cmd.Dir = root
	// Under -race, a clean exit sleeps atexit_sleep_ms (default 1s) to catch
	// at-exit races; the child is single-goroutine, so skip the wait.
	gorace := strings.TrimSpace(os.Getenv("GORACE") + " atexit_sleep_ms=0")
	cmd.Env = append(os.Environ(), runMainEnv+"=1", "GORACE="+gorace)
	out, err := cmd.CombinedOutput()
	if err == nil {
		return 0, string(out)
	}
	var exitErr *exec.ExitError
	if !errors.As(err, &exitErr) {
		t.Fatalf("running %s: %v", os.Args[0], err)
	}
	return exitErr.ExitCode(), string(out)
}

