func TestFirstMatch(t *testing.T) {
	re := regexp.MustCompile(`pin=([0-9.]+)`)
	tests := []struct {
		name    string
		content *string // nil leaves the file absent
		want    string
		wantErr string
	}{
		{
			name:    "returns the capture group of the first match",
			content: ptr("pin=1.2.3 then pin=9.9.9"),
			want:    "1.2.3",
		},
		{
			name:    "no match errors naming the file",
			content: ptr("nothing pinned here"),
			wantErr: "no match for",
		},
		{
			name:    "missing file errors",
			content: nil,
			wantErr: "no such file",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "pins.txt")
			if tt.content != nil {
				if err := os.WriteFile(path, []byte(*tt.content), 0o644); err != nil {
					t.Fatal(err)
				}
			}

			got, err := firstMatch(path, re)
			if tt.wantErr != "" {
				if err == nil {
					t.Fatalf("expected error containing %q, got %q", tt.wantErr, got)
				}
				if !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("error %q does not contain %q", err, tt.wantErr)
				}
				if tt.content != nil && !strings.Contains(err.Error(), path) {
					t.Errorf("error %q does not name the file %q", err, path)
				}
				return
			}
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if got != tt.want {
				t.Errorf("got %q, want %q", got, tt.want)
			}
		})
	}
}

