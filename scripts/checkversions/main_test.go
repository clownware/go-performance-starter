func TestAllMatchesAgree(t *testing.T) {
	re := regexp.MustCompile(`pin=([0-9.]+)`)
	tests := []struct {
		name    string
		files   map[string]string
		paths   []string
		want    string
		wantErr string
	}{
		{
			name:  "single file returns its pin",
			files: map[string]string{"a.yml": "pin=4.19.1"},
			paths: []string{"a.yml"},
			want:  "4.19.1",
		},
		{
			name:  "agreeing files return the shared pin",
			files: map[string]string{"a.yml": "pin=4.19.1", "b.yml": "x\npin=4.19.1\n", "c.yml": "pin=4.19.1"},
			paths: []string{"a.yml", "b.yml", "c.yml"},
			want:  "4.19.1",
		},
		{
			name:    "disagreeing files error naming both pins",
			files:   map[string]string{"a.yml": "pin=4.19.1", "b.yml": "pin=4.19.2"},
			paths:   []string{"a.yml", "b.yml"},
			wantErr: "pins 4.19.2 but an earlier file pins 4.19.1",
		},
		{
			name:    "missing file errors",
			files:   map[string]string{"a.yml": "pin=4.19.1"},
			paths:   []string{"a.yml", "missing.yml"},
			wantErr: "no such file",
		},
		{
			name:    "file without a match errors",
			files:   map[string]string{"a.yml": "pin=4.19.1", "b.yml": "no pin"},
			paths:   []string{"a.yml", "b.yml"},
			wantErr: "no match for",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			writeTree(t, root, tt.files)
			paths := make([]string, len(tt.paths))
			for i, p := range tt.paths {
				paths[i] = filepath.Join(root, p)
			}

			got, err := allMatchesAgree(re, paths...)
			if tt.wantErr != "" {
				if err == nil {
					t.Fatalf("expected error containing %q, got %q", tt.wantErr, got)
				}
				if !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("error %q does not contain %q", err, tt.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if got != tt.want {
				t.Errorf("got %q, want %q", got, tt.want)
			}
		})
	}
}

